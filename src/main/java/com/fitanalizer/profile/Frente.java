package com.fitanalizer.profile;

/**
 * Frente de carreira à qual uma skill ou experiência profissional pertence.
 * TRANSVERSAL cobre o que é transferível entre COMEX e TECH (gestão de
 * stakeholders, ambientes regulados, atenção a detalhe, operações
 * internacionais) — não é uma terceira frente concorrente, é o que conta
 * como evidência válida nas duas.
 */
public enum Frente {
    COMEX,
    TECH,
    TRANSVERSAL
}
